/**
 * \brief  AES operation context.
 *
 *         Holds the key material, selected algorithm, IV, and lifecycle
 *         state for one multipart AES operation.  Treat as opaque; use
 *         only through the nvt_psa_aes_*() API.
 */
typedef nvt_cipher_operation_t nvt_psa_aes_operation_t;

psa_status_t nvt_psa_aes_setup(nvt_psa_aes_operation_t *operation,
                               const psa_key_attributes_t *attributes,
                               const uint8_t *key,
                               size_t key_length,
                               psa_algorithm_t alg,
                               uint8_t is_encrypt);

psa_status_t nvt_psa_aes_set_iv(nvt_psa_aes_operation_t *operation,
                                const uint8_t *iv,
                                size_t iv_length);

psa_status_t nvt_psa_aes_update(nvt_psa_aes_operation_t *operation,
                                const uint8_t *input,
                                size_t input_length,
                                uint8_t *output,
                                size_t output_size,
                                size_t *output_length);

psa_status_t nvt_psa_aes_finish(nvt_psa_aes_operation_t *operation,
                                uint8_t *output,
                                size_t output_size,
                                size_t *output_length);

psa_status_t nvt_psa_aes_abort(nvt_psa_aes_operation_t *operation);

int nvt_aes_self_test(void);

